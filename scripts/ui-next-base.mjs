#!/usr/bin/env node
// UI Next (v4): generate ui-next/components/base.css from the design system's helmet (the one source, playbook rules 4 and 9).
// Source: ui-next/design-source/{helmet.html,gen.py,PIN} = cookbook design/2026-10-15-glass-redesign/generator at the pinned sha.
//   node scripts/ui-next-base.mjs                 write ui-next/components/base.css
//   node scripts/ui-next-base.mjs --check         exit 1 if base.css is not what the source generates
//   node scripts/ui-next-base.mjs --vendor <dir>  re-copy helmet.html + gen.py from a cookbook generator dir (then set PIN)
// base.css = helmet <style> + gen.EXTRA, verbatim (what every canvas board inlines as gen.H). The font <link> lives in ui-next/index.html.
// Node stdlib only. Status: provisional.
import { readFileSync, writeFileSync, copyFileSync, realpathSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
export const SRC = fileURLToPath(new URL("ui-next/design-source/", root));
export const OUTPUT = fileURLToPath(new URL("ui-next/components/base.css", root));
export const FONT_LINK = /<link rel="stylesheet" href="(https:\/\/fonts\.googleapis\.com\/[^"]+)">/;

export function render(helmet, genPy, pin) {
  const ex = genPy.match(/\nEXTRA = """\n([\s\S]*?)"""/);
  if (!ex) throw new Error("gen.py: EXTRA block not found");
  if (ex[1].includes("\\")) throw new Error("gen.py: EXTRA has escapes; render it with python instead");
  const st = helmet.match(/<style>\n([\s\S]*?)<\/style>\n<\/helmet>/);
  if (!st) throw new Error("helmet.html: <style> block not found");
  if (!FONT_LINK.test(helmet)) throw new Error("helmet.html: font <link> not found");
  return [
    "/* GENERATED by scripts/ui-next-base.mjs - do not edit by hand. */",
    `/* Source: 3d-review-cookbook @${pin} design/2026-10-15-glass-redesign/generator/helmet.html <style> + gen.py EXTRA (= gen.H, the helmet every canvas board inlines). */`,
    `/* Fonts: ${helmet.match(FONT_LINK)[1].replace(/&amp;/g, "&")} (linked from ui-next/index.html). Status: provisional. */`,
    st[1] + ex[1],
  ].join("\n");
}

export function generate() {
  const r = (f) => readFileSync(join(SRC, f), "utf8");
  return render(r("helmet.html"), r("gen.py"), r("PIN").trim());
}

if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  const v = process.argv.indexOf("--vendor");
  if (v > 0) { for (const f of ["helmet.html", "gen.py"]) copyFileSync(join(process.argv[v + 1], f), join(SRC, f)); console.log("vendored; update ui-next/design-source/PIN"); process.exit(0); }
  const css = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUTPUT, "utf8"); } catch {}
    if (current !== css) { console.error("ui-next/components/base.css is stale: run node scripts/ui-next-base.mjs"); process.exit(1); }
    console.log("ui-next/components/base.css is up to date");
  } else { writeFileSync(OUTPUT, css); console.log("wrote ui-next/components/base.css"); }
}
