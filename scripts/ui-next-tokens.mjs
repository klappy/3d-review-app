#!/usr/bin/env node
// UI Next (v4): generate ui-next/tokens.css from ui-next/tokens.source.json (the one source).
//   node scripts/ui-next-tokens.mjs           write ui-next/tokens.css
//   node scripts/ui-next-tokens.mjs --check   exit 1 if tokens.css is not what the source generates
// Node stdlib only. Status: provisional.
import { readFileSync, writeFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
export const SOURCE = fileURLToPath(new URL("ui-next/tokens.source.json", root));
export const OUTPUT = fileURLToPath(new URL("ui-next/tokens.css", root));

export function render(source) {
  const out = [
    "/* GENERATED by scripts/ui-next-tokens.mjs from ui-next/tokens.source.json - do not edit by hand. */",
    "/* Status: provisional. Contract: 3d-review-cookbook design/2026-10-15-glass-redesign/canvas/design-system.md section 1. */",
  ];
  for (const block of source.blocks) {
    if (typeof block.selector !== "string" || !block.decls || typeof block.decls !== "object") throw new Error("each block needs selector and decls");
    out.push("", `/* ${block.note ?? block.selector} */`, `${block.selector} {`);
    for (const [prop, value] of Object.entries(block.decls)) out.push(`  ${prop}: ${value};`);
    out.push("}");
  }
  return out.join("\n") + "\n";
}

export function generate() {
  return render(JSON.parse(readFileSync(SOURCE, "utf8")));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  const css = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUTPUT, "utf8"); } catch {}
    if (current !== css) { console.error("ui-next/tokens.css is stale: run node scripts/ui-next-tokens.mjs"); process.exit(1); }
    console.log("ui-next/tokens.css is up to date");
  } else {
    writeFileSync(OUTPUT, css);
    console.log("wrote ui-next/tokens.css");
  }
}
