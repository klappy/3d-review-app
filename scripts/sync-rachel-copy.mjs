#!/usr/bin/env node
// Emit ui-next/src/copy/rachel.js from the cookbook's generator/copy_rachel.py (Rachel 2026-10-19 copy), byte for byte.
//   node scripts/sync-rachel-copy.mjs <path/to/3d-review-cookbook/design/2026-10-15-glass-redesign/generator/copy_rachel.py> [out]
// Reads only the module-level string constants (C01, C02, CAPS, HOW, WHO) above the first `def`; Node stdlib only. Status: provisional.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const STR = /'((?:[^'\\]|\\.)*)'/g;
const unpy = (s) => JSON.parse(`"${s.replace(/\\'/g, "'").replace(/"/g, '\\"')}"`);
const strings = (src) => [...src.matchAll(STR)].map((m) => unpy(m[1]));

export function parse(py) {
  const head = py.split(/^def /m)[0];
  const block = (name) => {
    const m = head.match(new RegExp(`^${name} = ([\\s\\S]*?)(?=^\\w+ = |$(?![\\s\\S]))`, "m"));
    if (!m) throw new Error(`copy_rachel.py: no ${name}`);
    return strings(m[1]);
  };
  const pairs = (a) => { if (a.length % 2) throw new Error("odd pair list"); return Array.from({ length: a.length / 2 }, (_, i) => [a[2 * i], a[2 * i + 1]]); };
  const [C01] = block("C01"), [C02] = block("C02");
  const CAPS = Object.fromEntries(pairs(block("CAPS")));
  const HOW = pairs(block("HOW")), WHO = pairs(block("WHO"));
  if (Object.keys(CAPS).join() !== "team,community,church" || HOW.length !== 3 || WHO.length !== 3) throw new Error("copy_rachel.py: unexpected shape");
  const label = (t) => { if (!py.includes(`>${t}<`)) throw new Error(`copy_rachel.py: learn_more() has no ${t}`); return t; };
  return { C01, C02, CAPS, HOW, WHO, LEARN_MORE: label("Learn more"), HOW_IT_WORKS: label("How it works") };
}

export function emit(c, source = "generator/copy_rachel.py") {
  const j = (v) => JSON.stringify(v);
  return `// GENERATED by scripts/sync-rachel-copy.mjs from 3d-review-cookbook design/2026-10-15-glass-redesign/${source}. Do not edit.
// Rachel 2026-10-19 copy (sources/rachel-copy-2026-10-19/app-copy-edits.txt), word for word; C12 without the trajectory clause. Status: provisional.
export const C01 = ${j(c.C01)};
export const C02 = ${j(c.C02)};
export const CAPS = Object.freeze(${j(c.CAPS)});
export const HOW = Object.freeze(${j(c.HOW)});
export const WHO = Object.freeze(${j(c.WHO)});
export const LEARN_MORE = ${j(c.LEARN_MORE)};
export const HOW_IT_WORKS = ${j(c.HOW_IT_WORKS)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [src, out = fileURLToPath(new URL("../ui-next/src/copy/rachel.js", import.meta.url))] = process.argv.slice(2);
  if (!src) { console.error("usage: sync-rachel-copy.mjs <copy_rachel.py> [out]"); process.exit(2); }
  writeFileSync(out, emit(parse(readFileSync(src, "utf8"))));
  console.log(`wrote ${out}`);
}
