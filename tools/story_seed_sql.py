#!/usr/bin/env python3
"""seed/story/scenarios.json + seed/synthetic/answer-sets.json -> seed/story-scenarios.sql

Two demo story projects remixed from the existing synthetic persona submissions (no real data):
  A  Church lens high / Translation Team lens low, weakness "no documented translation brief" (TR-Q1),
     assessment next-step note carries a PLACEHOLDER video link (link not yet provided);
  B  the reverse.
Church lens = Involved-Pastor rows only: the product files tpl_consultant under perspective Church,
so consultant rows are left out to keep the lens split clean.
Each source row is copied from answer-sets.json; `set` pins named items to an option code and
`transform` floor|ceiling moves every scored single item to its lowest|highest scored option.
Every derivation is written into provenance_json. Rows are source='synthetic', names carry SYNTHETIC.
Apply AFTER migrations 0001-0004 and seed/synthetic.sql (demo owner + workspace). Idempotent
(INSERT OR IGNORE, deterministic ids). Local: wrangler d1 execute 3d-review-dev --local --file=seed/story-scenarios.sql
Usage: python3 tools/story_seed_sql.py [--check]   (--check: fail if the committed SQL is stale)
"""
import json, re, hashlib, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = f"{root}/seed/story-scenarios.sql"
OWNER, WS, AT = "person_mara", "ws_cedar", "2026-09-16T12:00:00.000Z"
q = lambda s: "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"

def templates():
    sql = open(f"{root}/migrations/0004_pinned_instruments.sql").read()
    tpl = {}
    for m in re.finditer(r"VALUES \('(tpl_[a-z_]*)', 2, '([^']*)', '[^']*', '[^']*', '(\[.*?\])', '(\{.*?\})', ", sql, re.S):
        items = json.loads(m.group(3).replace("''", "'"))
        tpl[m.group(2)] = {"id": m.group(1), "items": {i["id"]: i for i in items}}
    return tpl

def to_codes(rec, t):
    answers = {}
    for item_id, a in rec["answers"].items():
        it = t["items"].get(item_id)
        if not it: continue
        codes = []
        for text in a["selected"]:
            o = next((o for o in it.get("options", []) if o["text"] == text), None)
            if o: codes.append(o["code"])
            elif it["type"] == "text": codes.append(text)
        if codes: answers[item_id] = codes if it["type"] == "multi" else codes[0]
    return answers

def extreme(it, hi):
    scored = [o for o in it.get("options", []) if o.get("source_score") is not None]
    if it["type"] != "single" or not scored: return None
    return (max if hi else min)(scored, key=lambda o: o["source_score"])["code"]

def build():
    recs = json.load(open(f"{root}/seed/synthetic/answer-sets.json"))
    spec = json.load(open(f"{root}/seed/story/scenarios.json"))
    tpl = templates()
    out = ["-- Generated by tools/story_seed_sql.py from seed/story/scenarios.json + seed/synthetic/answer-sets.json. Do not hand-edit.",
           "-- SYNTHETIC demo story projects remixed from persona-generator submissions; no real participants, languages or field data."]
    rows = {"project": [], "language": [], "assessment": [], "survey": [], "grant": [], "response": []}
    for sc in spec["scenarios"]:
        pid, lid, aid = f"proj_story_{sc['id']}", f"lang_story_{sc['id']}", f"assess_story_{sc['id']}"
        rows["project"].append(f"INSERT OR IGNORE INTO project (id,workspace_id,name,organization,created_at,created_by) VALUES ({q(pid)},{q(WS)},{q(sc['name'])},'Synthetic persona org',{q(AT)},{q(OWNER)});")
        rows["language"].append(f"INSERT OR IGNORE INTO language (id,project_id,code,name,created_at) VALUES ({q(lid)},{q(pid)},'qaa',{q(sc['language'])},{q(AT)});")
        rows["assessment"].append(f"INSERT OR IGNORE INTO assessment (id,project_id,language_id,name,purpose,period,format,stage,notes_next_steps,created_at,created_by) VALUES ({q(aid)},{q(pid)},{q(lid)},{q(sc['name'] + ' cycle ' + sc['period'])},'Synthetic demo story (remixed persona-generator data; not field data)',{q(sc['period'])},'written','understand',{q(sc['notes_next_steps'])},{q(AT)},{q(OWNER)});")
        for scope, sid in (("project", pid), ("assessment", aid)):
            rows["grant"].append(f"INSERT OR IGNORE INTO \"grant\" (id,principal_id,scope_type,scope_id,role,created_at) VALUES ({q('grant_story_' + sid)},{q(OWNER)},{q(scope)},{q(sid)},'owner',{q(AT)});")
        for src in sc["sources"]:
            t = tpl[src["form"]]
            sid = f"survey_story_{sc['id']}_{t['id'][4:]}"
            rows["survey"].append(f"INSERT OR IGNORE INTO assessment_survey (id,assessment_id,template_id,template_version,state,collection_status,created_at) VALUES ({q(sid)},{q(aid)},{q(t['id'])},2,'selected','closed',{q(AT)});")
            picked = [r for r in recs if r["project_id"] == src["project"] and r["form_variant"] == src["form"] and ("cycle" not in src or r["assessment_cycle"] == src["cycle"])]
            if not picked: raise SystemExit(f"no source rows for {sc['id']} {src}")
            for r in picked:
                answers = to_codes(r, t)
                if src.get("transform"):
                    for item_id, it in t["items"].items():
                        c = extreme(it, src["transform"] == "ceiling")
                        if c: answers[item_id] = c
                for item_id, code in src.get("set", {}).items():
                    assert any(o["code"] == code for o in t["items"][item_id]["options"]), (item_id, code)
                    answers[item_id] = code
                for item_id, it in t["items"].items():
                    if item_id not in answers and it.get("required") is False: answers[item_id] = None
                key = f"story:{sc['id']}:{r['submission_id']}"
                rid = "resp_story_" + hashlib.sha256(key.encode()).hexdigest()[:20]
                prov = json.dumps({"synthetic": True, "story": sc["id"], "generator": "tools/story_seed_sql.py", "remixed_from": r["submission_id"],
                                   "persona": r["respondent_persona"], "upstream": "klappy/3d-quality-review@f042cde survey-pipeline/run_synthetic_pipeline.py",
                                   "transform": src.get("transform"), "set": src.get("set")}, sort_keys=True)
                rows["response"].append(f"INSERT OR IGNORE INTO response (id,assessment_survey_id,respondent_id,idempotency_key,answers_json,template_id,template_version,provenance_json,source,submitted_at) VALUES ({q(rid)},{q(sid)},{q('rsp_story_' + sc['id'] + '_' + r['respondent_persona'])},{q(key)},{q(json.dumps(answers, sort_keys=True))},{q(t['id'])},2,{q(prov)},'synthetic',{q(r['submitted_at'])});")
    for k in rows: out += rows[k]
    return "\n".join(out) + "\n", {k: len(v) for k, v in rows.items()}

if __name__ == "__main__":
    text, counts = build()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("story-scenarios.sql " + ("up to date" if ok else "STALE: run python3 tools/story_seed_sql.py")); sys.exit(0 if ok else 1)
    open(OUT, "w").write(text); print(json.dumps(counts))
